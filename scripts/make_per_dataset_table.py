"""K=16 per-dataset x per-backbone breakout of the per-backbone main table -> PER_DATASET_K16.md.

    PYTHONPATH=. python scripts/make_per_dataset_table.py

the per-backbone main table (the paper) is 8 methods x 4 backbones with the dataset
axis AVERAGED AWAY. This is the same evidence with that axis kept: 11 dataset
blocks, 8 methods, 4 backbones, 352 cells.

NO NEW COMPUTATION. It calls `rebuild_backbone_main.gather()`, the same loader
the table is built from, so the two cannot disagree -- averaging this file's
cells over datasets reproduces the per-backbone main table exactly, and the script
checks that before it writes anything.

`±` here is the sd over the 3 SEEDS OF ONE CELL. That is NOT the convention in
the per-backbone main table, where `±` is the sd over seeds of the 11-dataset mean,
paired within seed. The two are different quantities and this one is larger;
the file says so at the top so a reader cannot carry a number across.

WHY THIS EXISTS. The shot sweep found that at K=16 LE-GDA's per-dataset record is
weaker than the aggregate suggests -- 8 of 11 datasets on ViT-B/16, sign
p=0.227 -- and that observation rested on one backbone. The per-backbone sign
tests at the foot of this file settle it on all four.
"""

import argparse
import importlib.util
import sys
from math import comb
from statistics import mean, pstdev

spec = importlib.util.spec_from_file_location(
    "rb", "scripts/rebuild_backbone_main.py")
RB = importlib.util.module_from_spec(spec)
spec.loader.exec_module(RB)

BB, SEEDS = RB.BB, RB.SEEDS
ORDER = ["imagenet", "caltech101", "oxford_pets", "stanford_cars",
         "oxford_flowers", "food101", "fgvc", "sun397", "dtd", "eurosat",
         "ucf101"]
NICE = {"caltech101": "Caltech101", "dtd": "DTD", "eurosat": "EuroSAT",
        "fgvc": "FGVCAircraft", "food101": "Food101", "imagenet": "ImageNet",
        "oxford_flowers": "Flowers102", "oxford_pets": "OxfordPets",
        "stanford_cars": "StanfordCars", "sun397": "SUN397",
        "ucf101": "UCF101"}
# Prints to stdout by default: the repository keeps a single .md file
# (the README), so this generator does not create one. Redirect it, or
# pass --out to write somewhere outside the tree.


def sign_p(w, n):
    """Exact two-sided sign test."""
    return min(1.0, 2 * sum(comb(n, i) for i in range(w, n + 1)) / 2 ** n)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=None,
                    help="write to this path instead of stdout")
    args = ap.parse_args()
    R = RB.gather()
    labels = [l for l, _, _ in RB.ROWS]
    cell = {}                       # (label, bb, ds) -> (mean, sd) over seeds
    for lab in labels:
        src = R[RB.KEY[lab]]
        for bb in BB:
            for ds in ORDER:
                v = [src[(bb, ds, s)] for s in SEEDS if (bb, ds, s) in src]
                if len(v) != len(SEEDS):
                    sys.exit(f"REFUSING TO EMIT: {lab} {bb}/{ds} has "
                             f"{len(v)}/{len(SEEDS)} seeds")
                cell[(lab, bb, ds)] = (mean(v), pstdev(v))

    # consistency gate: averaging this file over datasets must reproduce the table
    published = {"Tip-Adapter": [70.20, 72.06, 72.88, 76.88],
                 "Proto-Adapter": [72.48, 73.64, 74.52, 78.34],
                 "GPCache (W+C)": [72.81, 75.26, 75.61, 79.42],
                 "Tip-Adapter-F": [75.50, 77.49, 77.61, 81.16],
                 "Proto-Adapter-F": [75.39, 76.67, 76.76, 80.39],
                 "GDA-CLIP (final-feature)": [75.56, 77.41, 77.69, 81.40],
                 "LE-GDA": [77.47, 79.68, 78.69, 82.31]}
    for lab, want in published.items():
        got = [mean(cell[(lab, bb, ds)][0] for ds in ORDER) for bb in BB]
        for g, w, bb in zip(got, want, BB):
            if abs(g - w) > 0.005:
                sys.exit(f"REFUSING TO EMIT: {lab}/{bb} averages to {g:.2f}, "
                         f"the per-backbone main table says {w:.2f}")

    # `Grad.` mirrors the per-backbone main table's own column. RB.ROWS carries it as
    # LaTeX ($\checkmark$ / --); render it for markdown here.
    GRAD = {lab: ("\u2713" if g.strip() not in ("--", "") else "\u2014")
            for lab, g, _ in RB.ROWS}
    # `Impl.` also mirrors the per-backbone main table: "orig." = the upstream authors'
    # own code under our protocol, "ours" = implemented here. The asymmetry is
    # load-bearing, not decoration -- see the plan sec.1.10.
    IMPL = {lab: (i if i.strip() != "--" else "\u2014") for lab, _, i in RB.ROWS}
    # LE-GDA is ours; the table names it so, as the per-backbone main table does.
    SHOW = {lab: ("LE-GDA (ours)" if lab == "LE-GDA" else lab)
            for lab, _, _ in RB.ROWS}

    L = []
    L += [f"# the per-backbone main table broken out per dataset — K = 16",
          "",
          "Generated by `scripts/make_per_dataset_table.py`. **Do not edit by "
          "hand — regenerate.**",
          "",
          "The plan's the per-backbone main table (§1.10) is 8 methods x 4 backbones "
          "with the dataset",
          "axis averaged away. This is the same evidence with that axis kept: "
          "**11 datasets x**",
          "**8 methods x 4 backbones = 352 cells**, 3 seeds each. Same loader "
          "(`rebuild_backbone_main.gather`),",
          "so the two cannot disagree; the script refuses to write unless "
          "averaging these cells",
          "over the 11 datasets reproduces every published column to 0.005.",
          "",
          "**`±` is the sd over the 3 seeds of THAT CELL.** In "
          "the per-backbone main table `±` means",
          "something else — the sd over seeds of the 11-dataset mean, paired "
          "within seed — and it",
          "is much smaller. Do not carry a number between the two files.",
          "",
          "Protocol is the plan's §2 invariant throughout: standard `testfull` "
          "splits, validation-only",
          "hyperparameter search, identical cached features per cell. "
          "`Tip-Adapter`/`Tip-Adapter-F` are",
          "the **upstream implementation** under our protocol (Run B); every "
          "other arm is ours.",
          "",
          "**Bold marks the best method in that column**, zero-shot excluded.",
          "**`Grad.`** is the per-backbone main table's own column: \u2713 marks the two "
          "gradient-trained arms",
          "(20 epochs), \u2014 the training-free ones. It is also what line "
          "style encodes in the shot-sweep",
          "figures \u2014 dashed is gradient-based and nothing else is dashed.",
          "**`Impl.`** is the per-backbone main table's other column: **orig.** means "
          "the upstream authors' own",
          "code run under our protocol, **ours** means implemented here. Only "
          "the two Tip-Adapter rows",
          "are `orig.`; every other arm is a reimplementation, and for the "
          "Proto-Adapter rows there is",
          "no upstream code to run at all \u2014 they are a reading of the "
          "paper's prose, audited in",
          "`patches/proto_adapter_design_note.md`. That asymmetry is real and "
          "is why those arms were",
          "calibrated against the published numbers before being reported.",
          ""]

    for ds in ORDER:
        L += [f"## {NICE[ds]}", "",
              "| Method | Grad. | Impl. | " + " | ".join(BB) + " | Mean |",
              "|---" * (len(BB) + 4) + "|"]
        best = {bb: max((cell[(l, bb, ds)][0] for l in labels
                         if l != "Zero-shot CLIP")) for bb in BB}
        for lab in labels:
            row = []
            for bb in BB:
                m, sd = cell[(lab, bb, ds)]
                t = f"{m:.2f}±{sd:.2f}"
                row.append(f"**{t}**" if lab != "Zero-shot CLIP"
                           and abs(m - best[bb]) < 1e-9 else t)
            mu = mean(cell[(lab, bb, ds)][0] for bb in BB)
            L.append(f"| {SHOW[lab]} | {GRAD[lab]} | {IMPL[lab]} | "
                     + " | ".join(row) + f" | {mu:.2f} |")
        L.append("")

    # ---- the question §1.16.3 raised, answered on all four backbones -------
    L += ["---", "",
          "## LE-GDA's per-dataset record, by backbone",
          "",
          "The shot-sweep analysis found LE-GDA wins 8 of 11 datasets on ViT-B/16 at K=16 "
          "(sign p = 0.227) —",
          "materially weaker than the aggregate row, and measured on one "
          "backbone. Here it is on",
          "all four.",
          "",
          "**The comparator is stricter here and the numbers are not "
          "interchangeable.** §1.16.3",
          "compares LE-GDA against **Tip-Adapter-F alone** (8/11 on ViT-B/16). "
          "This table compares it",
          "against the **best of all seven other methods, chosen per dataset**, "
          "which is the hardest",
          "comparison the evidence supports — and gives 7/11 on the same "
          "backbone. Neither is wrong;",
          "quote the one whose comparator you have stated.",
          "",
          "| backbone | datasets won | mean margin | sign p | worst dataset |",
          "|---|---|---|---|---|"]
    for bb in BB:
        d = []
        for ds in ORDER:
            le = cell[("LE-GDA", bb, ds)][0]
            other = max(cell[(l, bb, ds)][0] for l in labels
                        if l not in ("LE-GDA", "Zero-shot CLIP"))
            d.append((ds, le - other))
        w = sum(x > 0 for _, x in d)
        n = sum(x != 0 for _, x in d)
        worst = min(d, key=lambda t: t[1])
        L.append(f"| {bb} | {w}/{n} | {mean(x for _, x in d):+.2f} | "
                 f"{sign_p(max(w, n - w), n):.3f} | "
                 f"{NICE[worst[0]]} {worst[1]:+.2f} |")
    L += ["",
          "**No backbone reaches significance on breadth.** The aggregate row "
          "of the per-backbone main table",
          "is carried by margin SIZE on a few datasets, not by winning most of "
          "them. State it that way.",
          "",
          "**ImageNet is the worst dataset on all four backbones**, and it is "
          "the same loss each time:",
          "both trained arms beat LE-GDA there. Means over the four backbones "
          "— Proto-Adapter-F 67.35,",
          "Tip-Adapter-F 67.24, LE-GDA 66.63, GDA-CLIP 66.47. A training-free "
          "Gaussian arm losing to",
          "gradient-trained cache adapters on the largest, most class-dense "
          "dataset is a consistent",
          "result across all four backbones, not a single-cell wobble, and the "
          "paper should say so",
          "rather than let the 11-dataset mean absorb it.",
          ""]

    text = "\n".join(L)
    if args.out:
        open(args.out, "w").write(text)
        print(f"wrote {args.out}", file=sys.stderr)
    else:
        print(text)
    print(f"# {len(ORDER)} datasets x {len(labels)} methods x {len(BB)} "
          f"backbones = {len(ORDER)*len(labels)*len(BB)} cells; consistency\n"
          f"# gate passed: dataset-averaged columns reproduce the main table.",
          file=sys.stderr)


if __name__ == "__main__":
    main()
